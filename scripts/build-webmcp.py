#!/usr/bin/env python3
"""Generate /webmcp.js: WebMCP tools that let in-browser AI agents use phongminhto.com.

WebMCP (W3C Web Machine Learning CG draft) lets a page declare tools through
document.modelContext.registerTool. Browsers without the API skip the file silently.
All tools are read-only: they return facts and links, they never submit, buy or book.

Rebuild after adding a guide or changing the buying-process steps:
  python3 scripts/build-webmcp.py
Sources: llms.txt (guides), quy-trinh-mua-nha-texas/src/diagram-{vi,en}.json (14 steps).
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def guides():
    out = []
    section = None
    for line in (ROOT / "llms.txt").read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            section = line[3:].strip()
            continue
        m = re.match(r"- \[(.+?)\]\((https://phongminhto\.com/[^)]*)\): (.+)", line)
        if m and section == "Guides":
            out.append({"title": m.group(1), "url": m.group(2), "summary": m.group(3)})
    return out


def steps(lang):
    d = json.loads((ROOT / f"quy-trinh-mua-nha-texas/src/diagram-{lang}.json").read_text(encoding="utf-8"))
    out = {}
    for s in d["steps"]:
        m = re.match(r"(\d+)\.\s*(.+)", s.get("label", ""))
        if m:
            out[int(m.group(1))] = {"title": m.group(2), "detail": s.get("description", "")}
    return dict(sorted(out.items()))


PROFILE = {
    "name": "Phong Minh To",
    "role": "Licensed Texas REALTOR®",
    "brokerage": "eXp Realty",
    "license": "TREC #843757",
    "areas": "Dallas–Fort Worth, Sherman, Denison, Grayson, Collin and Denton counties, Texas",
    "languages": "Vietnamese, English",
    "serves": "Vietnamese and relocating families buying homes in Texas",
    "phone": "(737) 242-9999",
    "email": "info@phongminhto.com",
    "booking": "https://tidycal.com/phongto",
    "website": "https://phongminhto.com/",
    "disclaimer": "Information on this site is for reference only and is not financial or legal advice.",
}

JS = r"""/* WebMCP tools for phongminhto.com. Generated by scripts/build-webmcp.py; do not edit by hand. */
(function () {
  var mc = document.modelContext;
  if (!mc || typeof mc.registerTool !== 'function') return; // browser has no WebMCP: do nothing
  var PROFILE = __PROFILE__;
  var GUIDES = __GUIDES__;
  var STEPS = { vi: __STEPS_VI__, en: __STEPS_EN__ };
  var RO = { readOnlyHint: true, untrustedContentHint: false, consequentialHint: false };
  function norm(s) { return String(s || '').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/đ/g, 'd'); }
  function noop() {}
  mc.registerTool({
      name: 'get_realtor_profile',
      title: 'Realtor profile',
      description: 'Return who runs this site: Phong Minh To, a licensed Texas REALTOR with eXp Realty (TREC #843757), service areas, languages and contact details.',
      inputSchema: { type: 'object', properties: {} },
      annotations: RO,
      execute: async function () { return JSON.stringify(PROFILE); }
    }).catch(noop);
  mc.registerTool({
      name: 'find_guide',
      title: 'Find a guide',
      description: 'Find Phong To\'s guides about buying a home in Texas by topic, e.g. homestead exemption, MUD or PID tax, buying process, first-time buyer, California to Texas, Sherman. Accepts Vietnamese or English.',
      inputSchema: { type: 'object', properties: { topic: { type: 'string', description: 'Topic or question, Vietnamese or English' } }, required: ['topic'] },
      annotations: RO,
      execute: async function (args) {
        var words = norm(args && args.topic).split(/[^a-z0-9]+/).filter(function (w) { return w.length > 2; });
        if (!words.length) return 'Please give a topic, e.g. "homestead" or "MUD tax".';
        var hits = GUIDES.map(function (g) {
          var hay = norm(g.title + ' ' + g.summary + ' ' + g.url);
          return { g: g, score: words.filter(function (w) { return hay.indexOf(w) >= 0; }).length };
        }).filter(function (h) { return h.score > 0; }).sort(function (a, b) { return b.score - a.score; });
        if (!hits.length) return 'No guide matches "' + args.topic + '". All guides: ' + GUIDES.map(function (g) { return g.url; }).join(', ');
        return JSON.stringify(hits.slice(0, 3).map(function (h) { return { title: h.g.title, url: h.g.url, summary: h.g.summary }; }));
      }
    }).catch(noop);
  mc.registerTool({
      name: 'explain_buying_step',
      title: 'Explain a Texas home-buying step',
      description: 'Explain one of the 14 steps of buying an existing home with a mortgage in Texas (TREC contract), from 1 pre-approval to 14 keys and homestead. Reference only, not legal or financial advice.',
      inputSchema: { type: 'object', properties: {
        step: { type: 'integer', minimum: 1, maximum: 14, description: 'Step number 1 to 14' },
        language: { type: 'string', enum: ['vi', 'en'], description: 'Answer language, vi or en (default vi)' }
      }, required: ['step'] },
      annotations: RO,
      execute: async function (args) {
        var lang = args && args.language === 'en' ? 'en' : 'vi';
        var n = Number(args && args.step);
        var s = STEPS[lang][n];
        if (!s) return 'Step must be a whole number from 1 to 14.';
        return JSON.stringify({ step: n, title: s.title, detail: s.detail, more: 'https://phongminhto.com/quy-trinh-mua-nha-texas/#' + (lang === 'vi' ? 'buoc-' : 'step-') + n, note: PROFILE.disclaimer });
      }
    }).catch(noop);
  mc.registerTool({
      name: 'get_relocation_guide',
      title: 'Texas relocation guide (PDF)',
      description: 'Return the link to Phong To\'s free 2026 Texas relocation guide PDF for Vietnamese families (cost of living, property tax, school districts, checklists).',
      inputSchema: { type: 'object', properties: {} },
      annotations: RO,
      execute: async function () { return JSON.stringify({ title: 'Cẩm nang an cư Texas 2026', url: 'https://phongminhto.com/downloads/cam-nang-an-cu-texas-2026.pdf' }); }
    }).catch(noop);
  mc.registerTool({
      name: 'get_contact_info',
      title: 'Contact Phong To',
      description: 'Return Phong To\'s phone, email and the page where the user can choose a time for a free 1:1 consultation. Returns information only.',
      inputSchema: { type: 'object', properties: {} },
      annotations: RO,
      execute: async function () { return JSON.stringify({ schedule_page: PROFILE.booking, phone: PROFILE.phone, email: PROFILE.email }); }
    }).catch(noop);
})();
"""


def main():
    js = (JS.replace("__PROFILE__", json.dumps(PROFILE, ensure_ascii=False))
            .replace("__GUIDES__", json.dumps(guides(), ensure_ascii=False))
            .replace("__STEPS_VI__", json.dumps(steps("vi"), ensure_ascii=False))
            .replace("__STEPS_EN__", json.dumps(steps("en"), ensure_ascii=False)))
    (ROOT / "webmcp.js").write_text(js, encoding="utf-8")
    print("webmcp.js written:", len(guides()), "guides,", len(steps("vi")), "steps")


if __name__ == "__main__":
    main()
